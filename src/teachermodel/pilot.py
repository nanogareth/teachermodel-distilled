@dataclass
class Result:
    lines: list[str] = field(default_factory=list)

    def add(self, line: str) -> None:
        self.lines.append(line)


def _dump(doc: dict[str, Any], header: str) -> str:
    return header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


def _write(path: Path, text: str, force: bool, res: Result, store: Path) -> None:
    rel = path.relative_to(store).as_posix()
    data = text.encode("utf-8")
    if path.exists():
        if path.read_bytes() == data:
            res.add(f"unchanged  {rel}")
            return
        if not force:
            res.add(f"kept       {rel} (differs from the generated one; --force replaces it)")
            return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    res.add(f"wrote      {rel}")


def _set_user_env(value: str) -> None:
    """Set the user environment variable and tell running programs (Windows only)."""
    import ctypes
    import winreg

    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_SET_VALUE) as key:
        winreg.SetValueEx(key, config.ENV_VAR, 0, winreg.REG_SZ, value)
    hwnd_broadcast, wm_settingchange, smto_abortifhung = 0xFFFF, 0x001A, 0x0002
    ctypes.windll.user32.SendMessageTimeoutW(hwnd_broadcast, wm_settingchange, 0, "Environment", smto_abortifhung,
                                             5000, ctypes.byref(ctypes.c_ulong()))


def _user_env() -> str | None:
    if sys.platform != "win32":
        return os.environ.get(config.ENV_VAR)
    import winreg

    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
            return str(winreg.QueryValueEx(key, config.ENV_VAR)[0])
    except OSError:
        return None


PILOT_DRIVER = "pilot"


class PilotError(Exception):
    """pilot-sign refused its input; the message names what to fix."""


def _signoff_text(path: Path) -> tuple[str, str]:
    """(file name, text) of the sign-off in `path`: the file itself, or, for the `.eml` draft a page's Save downloads,
    the one `.json` file attached to it (owner, 2026-10-27: generated signers use the same Save button)."""
    try:
        data = path.read_bytes()
    except OSError as exc:
        raise PilotError(f"{path}: not readable") from exc
    if path.suffix.lower() != ".eml":
        try:
            return path.name, data.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise PilotError(f"{path}: not readable as JSON") from exc
    from email import message_from_bytes, policy

    msg = message_from_bytes(data, policy=policy.default)
    found = [a for a in msg.iter_attachments() if (a.get_filename() or "").lower().endswith(".json")]
    if len(found) != 1:
        raise PilotError(f"{path}: a draft must carry exactly one .json sign-off file, found {len(found)}")
    try:
        return found[0].get_filename(), found[0].get_payload(decode=True).decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PilotError(f"{path}: the attached sign-off file is not UTF-8") from exc


def pilot_sign(private: Path, files: list[Path], *, now: Any = None, root: Path = ROOT, include_owner: bool = False) -> Any:
    """Ingest sign-offs saved from the pages of generated signers, in a pilot store only (decision 0016).

    Generated people and instructors have example.com addresses, so no mail can come from them. This wraps their
    sign-off files in a receipt of the `pilot` driver for a one-op plan (the sign-off mailbox read), as if each had
    been mailed from the signer's own generated address, and ingests it with every check of a real receipt. It refuses:
    - any store whose settings do not say `pilot: true`;
    - any sign-off whose signer has no generated address in the store: real people's sign-offs (yours, for the office
      roles) come through the mailbox and the connector as usual, which is what the pilot tests.
    `teachermodel ingest` never accepts the pilot driver, and a pilot receipt does not count as a read of the real
    sign-off mailbox, so the connector's next search still starts before any real sign-off it has not seen.
    `include_owner` (dev-autosign only, owner 2026-10-27) also takes the pilot owner's sign-offs, sent as from the
    owner's address, for development runs that do not test the mailbox."""
    import json
    from datetime import datetime, timezone

    from . import app, bridge, setup

    private = Path(private)
    try:
        settings = setup.load_settings(private)
    except setup.SetupError as exc:
        raise PilotError(str(exc)) from exc
    if settings.get("pilot") is not True:
        raise PilotError("pilot-sign works only in a pilot store (settings 'pilot: true', decision 0016); sign-offs "
                         "in this store come through the sign-off mailbox")
    if not files:
        raise PilotError("give at least one sign-off file")
    now = now or datetime.now(timezone.utc).replace(microsecond=0)
    st = app.load_state(private, root)
    generated: dict[str, list[str]] = {}  # signer URI -> its generated addresses
    for email, idents in st.identities.items():
        for ident in idents:
            if roster_module.is_reserved_email(email) or (include_owner and ident["uri"] == OWNER):
                generated.setdefault(ident["uri"], []).append(email)

    messages = []
    for path in files:
        name, text = _signoff_text(Path(path))
        try:
            doc = json.loads(text)
        except ValueError as exc:
            raise PilotError(f"{path}: not readable as JSON") from exc
        if not isinstance(doc, dict) or doc.get("schema") != app.SIGNOFF_SCHEMA:
            raise PilotError(f"{path}: not a sign-off file ({app.SIGNOFF_SCHEMA})")
        signer = doc.get("signer")
        if signer not in generated:
            raise PilotError(f"{path}: {signer} is not a generated signer in this store; a real person's sign-off "
                             "goes through the sign-off mailbox")
        # A generated instructor who also holds a mapped role (the coach) has two addresses: send from the one whose
        # identity carries the role the step asks for, as that person would.
        role = (st.step_defs.get(doc.get("step")) or {}).get("role")
        senders = sorted(generated[signer], key=lambda email: (not any(
            ident["uri"] == signer and role in ident.get("roles", ()) for ident in st.identities[email]), email))
        messages.append({"sender": senders[0], "subject": f"[tm-signoff {doc.get('id')}]",
                         "received": now.isoformat(timespec="seconds"),
                         "attachments": [{"name": name, "content": text}]})

    stamp = now.strftime("%Y%m%dT%H%M%SZ")
    plan, _ = bridge.build_plan([], settings=app.plan_settings(st, now.date()), recipients={},
                                created=now.isoformat(timespec="seconds"))
    digest = bridge.plan_sha256(plan)
    (private / "plans").mkdir(parents=True, exist_ok=True)
    (private / "plans" / f"pilot-{stamp}.json").write_text(json.dumps(plan, indent=2) + "\n", encoding="utf-8",
                                                           newline="\n")
    receipt = {"schema": app.RECEIPT_SCHEMA, "plan_sha256": digest, "driver": PILOT_DRIVER,
               "run_at": now.isoformat(timespec="seconds"),
               "results": [{"op_id": op["op_id"], "status": "ok", "data": {"messages": messages}}
                           for op in plan["ops"]]}
    (private / "receipts").mkdir(parents=True, exist_ok=True)
    path = private / "receipts" / f"pilot-{stamp}.json"
    path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8", newline="\n")
    return app.do_ingest(private, path, now=now, allowed_drivers=(*app.DEFAULT_DRIVERS, PILOT_DRIVER), root=root)


def init_pilot(store: Path, *, owner_name: str, owner_email: str, force: bool = False, set_env: bool = True,
               root: Path = ROOT) -> Result:
    """Create or complete the pilot store at `store`. Raises config.ConfigError on a bad path or owner."""
    store = config._assert_not_appdata(config.assert_outside_repo(store))
    if not owner_name.strip():
        raise config.ConfigError("--owner-name is empty")
    if roster_module.is_reserved_email(owner_email) or "@" not in owner_email:
        raise config.ConfigError("--owner-email must be your own work mailbox: sign-off pages for the office roles "
                                 "go to it, and sign-offs come back from it")
    if owner_email.rsplit("@", 1)[1].strip().rstrip(".").lower() in PERSONAL_MAIL_DOMAINS:
        raise config.ConfigError("--owner-email is a personal mailbox: the connector driver reads your work "
                                 "Microsoft 365 mail only, so give your work address")
    res = Result()
    for d in LAYOUT:
        (store / d).mkdir(parents=True, exist_ok=True)
    res.add(f"layout     {', '.join(LAYOUT)}")

    settings = settings_doc(store, owner_email)
    current = store / "settings.yaml"
    if current.is_file():  # the development toggle (`teachermodel dev-mode`) is the owner's, not generated
        kept = (yaml.safe_load(current.read_text(encoding="utf-8")) or {}).get("dev_autosign")
        if isinstance(kept, bool):
            settings["dev_autosign"] = kept
    people = generated_people(owner_name, owner_email)
    roster = generated_roster()
    outcomes = generated_outcomes()
    for doc, schema in ((settings, "settings.schema.json"), (people, "people.schema.json"),
                        (roster, "roster.schema.json"), (outcomes, "outcome-import.schema.json")):
        errors = validate(doc, schema, root)
        if errors:  # a generator defect, never the user's input
            raise RuntimeError(f"init-pilot generated an invalid {schema}: {errors}")
    errors = roster_module.check_roster(roster, root) + roster_module.pilot_refusals(roster)
    if errors:
        raise RuntimeError(f"init-pilot generated a roster that would be refused: {errors}")

    gen = "# Generated by teachermodel init-pilot (decision 0016). Pilot data only.\n"
    _write(store / "README.md", README, force, res, store)
    _write(store / "settings.yaml", _dump(settings, gen), force, res, store)
    _write(store / "identities" / "people.yaml", _dump(people, gen), force, res, store)
    _write(store / "inputs" / "roster.yaml", _dump(roster, gen), force, res, store)
    _write(store / "inputs" / "outcomes.yaml", _dump(outcomes, gen), force, res, store)
    _write(store / "inputs" / "calibration-reference.yaml", _dump(generated_reference(root), gen), force, res, store)
    _write(store / "inputs" / "retention.yaml", _dump(generated_retention(root), gen), force, res, store)
    config.people(store)  # the people list as written, or as kept, must load

    current = _user_env()
    if current and Path(current).resolve() == store:
        res.add(f"env        {config.ENV_VAR} already points here")
    elif not set_env:
        res.add(f"env        {config.ENV_VAR} is {current or 'unset'}; not changed (--no-set-env)")
    elif sys.platform != "win32":
        res.add(f"env        set {config.ENV_VAR}={store} in your shell profile (not Windows)")
    else:
        _set_user_env(str(store))
        res.add(f"env        {config.ENV_VAR} set to {store} (was {current or 'unset'}); new terminals see it")
    return res
