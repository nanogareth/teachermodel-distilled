"""`teachermodel init-pilot`: set up a pilot private store with generated data (decision 0016).

One command replaces the manual setup: it creates the store layout, writes `settings.yaml` with `pilot: true`, writes a
people list in which the owner holds every office role and generated people hold the instructor-linked roles, and puts
generated input files (a roster and an outcome export) under `inputs/` for the owner to import when the workflow
allows. It also points the user environment variable at the store.

Everything it writes is deterministic. A file that already exists is kept: an identical one is reported as
unchanged, a different one as kept unless `force` is given. It never touches events, sign-offs or imports.
Every generated instructor and generated person uses an example.com address (RFC 2606), so the pilot guard in
roster import accepts the roster and no generated address can reach a real mailbox.
"""

