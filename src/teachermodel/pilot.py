def _uri(slug: str) -> str:
    return f"tm:instructor/{slug}"


def generated_roster() -> dict[str, Any]:
    """A roster@2 of generated instructors: three clearers (W4 needs two, W2 two observers), and one instructor at
    each other level, including a Californian (overlay). Only jurisdictions with a profile (IE, US-CA)."""
    rows = []
    for n, (slug, kind, level, juris, regions, langs) in enumerate(_INSTRUCTORS, start=1):
        row: dict[str, Any] = {
            "instructor": _uri(slug),
            "identity": {"name": f"Pilot {_TITLES[kind]} {n:02d}", "email": f"pilot.{slug}@example.com"},
            "type": kind,
            "organisation": {"partner": "tm:org/example-partner", "contractor": "tm:org/example-training-ltd"}
                            .get(kind, "tm:org/example"),
            "level": level,
            "languages": langs,
            "regions": regions,
            "jurisdiction": juris,
            "engagement": {"start": "2025-01-06", "status": "active"},
        }
        if kind == "sme-engineer":
            row["engagement"].update(manager=OWNER, protected_hours_per_month=16)
        if kind == "contractor":
            row["engagement"].update(end="2027-06-30", agreement_ref=f"agreements/{slug}-pilot")
        if kind == "partner":
            row["engagement"]["nominated_by"] = OWNER
        if level in _DELIVERING:
            row["delivers"] = [{"unit": UNIT, "modes": ["in-person", "remote", "hybrid"], "last_delivered": "2026-10-15"}]
        rows.append(row)
    return {"schema": "tm:contract/roster@2", "as_of": AS_OF, "source": "Generated by teachermodel init-pilot",
            "prepared_by": OWNER, "instructors": rows}


def generated_outcomes() -> dict[str, Any]:
    """An outcome-import@1 export with aggregates only, for the instructors who deliver."""
    deliveries = []
    scores = [72.0, 68.5, 75.0, 70.0, 61.5, 66.0]
    delivering = [r for r in _INSTRUCTORS if r[2] in _DELIVERING]
    for n, (slug, *_rest) in enumerate(delivering):
        deliveries.append({
            "delivery_ref": f"pilot-delivery-{n + 1:03d}", "instructor": _uri(slug), "unit": UNIT, "mode": "remote",
            "delivered_on": "2026-10-15", "learners_assessed": 14 + n, "score": scores[n % len(scores)],
            "baseline": 70.0,
        })
    return {"schema": "tm:contract/outcome-import@1", "source": "Generated by teachermodel init-pilot",
            "exported_at": "2026-10-26T09:00:00Z", "deliveries": deliveries}


def generated_reference(root: Path = ROOT) -> dict[str, int]:
    """A calibration answer sheet for `teachermodel open-exercise`: a score 1-4 for every framework domain, cycling
    so the clearers' scores can match or miss it."""
    return {d: (2, 3, 3, 2, 4)[n % 5] for n, d in enumerate(domain_ids(root))}


GENERATED_RETENTION_MONTHS = 24


def generated_retention(root: Path = ROOT) -> dict[str, Any]:
    """A retention@2 table for the pilot (owner, 2026-10-27: the pilot stopped at retention-approved): one base entry
    per category and purpose pair that purposes.yaml uses, each with the base profile's proposed basis for the purpose.
    The periods are generated, not set with legal advice; `setup.retention_file` reads this table only in a pilot store,
    and standards/retention.yaml stays as it is."""
    purposes = privacy.load_purposes(root)
    _, profile = privacy.base_profile(root)
    basis = {p["id"]: p["proposed_basis"][profile["id"]]["basis"] for p in purposes["purposes"]}
    return {
        "schema_version": 2,
        "status": "draft",
        "basis": "generated for the pilot (decision 0016); not set with legal advice",
        "entries": [{"category": c, "purpose": p, "period_months": GENERATED_RETENTION_MONTHS,
                     "starts": "the end of the instructor's engagement",
                     "reason": "Generated period for the pilot, which holds generated data only; not a real period.",
                     "basis": basis[p]}
                    for c, p in privacy.required_pairs(purposes)],
    }


def generated_people(owner_name: str, owner_email: str) -> dict[str, Any]:
    """The owner with every office role, and one generated person per instructor-linked role: a clearer person
    mapped to each clearer instructor, and a coach mapped to the cleared instructor who coaches the two below."""
    people: list[dict[str, Any]] = [{"person": OWNER, "name": owner_name, "email": owner_email, "roles": OWNER_ROLES}]
    for slug, _kind, level, *_ in _INSTRUCTORS:
        if level == "clearer":
            people.append({"person": f"tm:person/pilot-clearer-{slug}", "name": f"Pilot Clearer {slug}",
                           "email": f"pilot.clearer.{slug}@example.com", "roles": ["clearer"],
                           "instructor": _uri(slug)})
    people.append({"person": "tm:person/pilot-coach-b7x5c", "name": "Pilot Coach b7x5c",
                   "email": "pilot.coach.b7x5c@example.com", "roles": ["coach"], "instructor": _uri("b7x5c"),
                   "coaches": [_uri("z2p8j"), _uri("f9w3m")]})
    return {"schema": "tm:contract/people@1", "people": people}


def settings_doc(store: Path, owner_email: str) -> dict[str, Any]:
    return {"schema": "tm:contract/settings@1", "library": store.name, "mailbox": owner_email, "it_email": owner_email,
            "dpo_email": owner_email, "notice_version": "2026-11", "pilot": True}


