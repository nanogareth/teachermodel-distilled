"""`teachermodel claude-kit`: the Claude buttons' deployment files, generated from standards/chains.yaml (decision 0029).

    claude-kit --out <dir> [--connector salesforce=https://...]

Writes, for the deploying organisation's tenant (nothing here calls the Claude API):

  agents/<button>.md            one Managed Agents agent per acting button, for `ant apply`: the model, the MCP servers,
                                one toolset per server with everything off, read tools always_allow, write tools
                                always_ask (the person who pressed approves each call); the body is the system prompt
  environments/buttons.yaml     limited networking, the declared MCP servers only
  drafting/<button>.json        the Messages API request body per drafting button: read-only allowlisted toolsets,
                                structured output against contracts/drafts/<button>.schema.json, a cached system
                                prompt; `{{projection}}` and `{{token:<server>}}` are filled per press
  prompts/<button>.md           every button's system prompt
  manifest.json                 every file's sha256, the beta headers, and what is still to fill (connector URLs the
                                directory does not list)

Deterministic: the same chains.yaml writes the same bytes, so a reviewer sees exactly what changed.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import yaml

from . import interventions
from .standards import ROOT, load_schema

BETAS = {"draft": ["mcp-client-2026-09-15", "server-side-fallback-2026-07-01"],
         "draft-no-connectors": ["server-side-fallback-2026-07-01"]}
MAX_TOKENS = 16000
API_VERSION = "2026-10-21"  # the current Messages API version; these requests send no temperature, top_p or top_k


class KitError(Exception):
    pass


def placeholder(server: str) -> str:
    return f"https://set-by-it.invalid/{server}"  # the directory lists no public URL; IT fills it (manifest "to_fill")


def system_prompt(button: dict[str, Any], never: list[str]) -> str:
    acting = button["kind"] == "act"
    lines = [f"You are the \"{button['title']}\" button for a technical training function.", "", button["task"], "",
             "You are given one view as JSON: the part of the record the person who pressed this button may see. Use "
             "it and the connector tools you have, and nothing else.", "", "Rules:"]
    lines += [f"- {rule}" for rule in never]
    if acting:
        lines += ["- Each write you make is shown to the person who pressed this button, field by field, before it "
                  "runs. If they deny it, read their reason, then correct the call or stop.",
                  "- Make the fewest writes that do the job; check with the read tools that the thing does not exist "
                  "already."]
    else:
        lines += ["- Return only the JSON your output format asks for. A person reads it, can change it, and sends it "
                  "themselves."]
    lines += ["- Write in plain words and short sentences. Use the ids in the view, never names."]
    return "\n".join(lines) + "\n"


def _url(doc: dict[str, Any], server: str, overrides: dict[str, str]) -> str:
    return overrides.get(server) or doc["connectors"][server]["url"] or placeholder(server)


def agent_file(doc: dict[str, Any], button: dict[str, Any], overrides: dict[str, str]) -> str:
    servers = sorted(set(button["reads"]) | set(button.get("writes") or {}))
    toolsets = []
    for server in servers:
        configs = [{"name": t, "enabled": True, "permission_policy": {"type": "always_allow"}}
                   for t in button["reads"].get(server, [])]
        configs += [{"name": t, "enabled": True, "permission_policy": {"type": "always_ask"}}
                    for t in (button.get("writes") or {}).get(server, [])]
        toolsets.append({"type": "mcp_toolset", "mcp_server_name": server,
                         "default_config": {"enabled": False, "permission_policy": {"type": "always_ask"}},
                         "configs": configs})
    front = {"name": f"teachermodel {button['id']}", "model": doc["model"],
             "mcp_servers": [{"type": "url", "name": s, "url": _url(doc, s, overrides)} for s in servers],
             "tools": toolsets}
    head = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, width=120)
    return f"---\n# agents/{button['id']}.md: generated by `teachermodel claude-kit` from standards/chains.yaml\n" \
           f"{head}---\n\n{system_prompt(button, doc['never'])}"


UNSUPPORTED = ("minLength", "maxLength", "minItems", "maxItems", "pattern", "minimum", "maximum", "multipleOf")


def api_schema(schema: Any) -> Any:
    """The draft schema as structured outputs accept it: no string-length, array-count or numeric constraints and no
    pattern (the SDKs strip these and validate client-side; a flow calling the HTTP API must send them stripped), and a
    type list as anyOf. The full schema still holds: `teachermodel check-draft` checks every draft that comes back."""
    if isinstance(schema, list):
        return [api_schema(s) for s in schema]
    if not isinstance(schema, dict):
        return schema
    out = {k: api_schema(v) for k, v in schema.items() if k not in UNSUPPORTED and not k.startswith("$")}
    if isinstance(out.get("type"), list):
        types = out.pop("type")
        out = {"anyOf": [{**out, "type": t} if t != "null" else {"type": "null"} for t in types]}
    return out


def drafting_request(doc: dict[str, Any], button: dict[str, Any], overrides: dict[str, str],
                     root: Path = ROOT) -> dict[str, Any]:
    schema = load_schema(f"drafts/{button['id']}.schema.json", root)
    body: dict[str, Any] = {
        "model": doc["model"],
        "max_tokens": MAX_TOKENS,
        "system": [{"type": "text", "text": system_prompt(button, doc["never"]), "cache_control": {"type": "ephemeral"}}],
        "output_config": {"effort": button["effort"],
                          "format": {"type": "json_schema",
                                     "schema": api_schema(schema)}},
        "fallbacks": "default",
        "messages": [{"role": "user", "content": "{{projection}}"}],
    }
    servers = sorted(button["reads"])
    if servers:
        body["mcp_servers"] = [{"type": "url", "name": s, "url": _url(doc, s, overrides),
                                "authorization_token": f"{{{{token:{s}}}}}"} for s in servers]
        body["tools"] = [{"type": "mcp_toolset", "mcp_server_name": s, "default_config": {"enabled": False},
                          "configs": {t: {"enabled": True} for t in button["reads"][s]}} for s in servers]
    betas = BETAS["draft" if servers else "draft-no-connectors"]
    return {"anthropic-version": API_VERSION, "anthropic-beta": ",".join(betas), "body": body}


def environment() -> str:
    env = {"name": "teachermodel-buttons",
           "config": {"type": "cloud", "networking": {"type": "limited", "allow_mcp_servers": True}}}
    return "# environments/buttons.yaml: generated by `teachermodel claude-kit`\n" + yaml.safe_dump(env, sort_keys=False)


def build(overrides: dict[str, str] | None = None, root: Path = ROOT) -> dict[str, str]:
    """Relative path -> file text, for every file in the kit."""
    overrides = overrides or {}
    doc = interventions.chains_doc(root)
    if found := interventions.problems(doc, root):
        raise KitError("standards/chains.yaml: " + "; ".join(found))
    if unknown := sorted(set(overrides) - set(doc["connectors"])):
        raise KitError(f"no connector {', '.join(unknown)} in standards/chains.yaml")
    files: dict[str, str] = {"environments/buttons.yaml": environment()}
    for b in doc["buttons"]:
        files[f"prompts/{b['id']}.md"] = system_prompt(b, doc["never"])
        if b["kind"] == "act":
            files[f"agents/{b['id']}.md"] = agent_file(doc, b, overrides)
        else:
            files[f"drafting/{b['id']}.json"] = json.dumps(drafting_request(doc, b, overrides, root), indent=2) + "\n"
    used = {s for b in doc["buttons"] for s in (*b["reads"], *(b.get("writes") or {}))}
    to_fill = sorted(s for s in used if not (overrides.get(s) or doc["connectors"][s]["url"]))
    manifest = {"generated_from": "standards/chains.yaml",
                "chains_sha256": hashlib.sha256((Path(root) / interventions.CHAINS).read_bytes()).hexdigest(),
                "model": doc["model"], "anthropic_version": API_VERSION, "betas": BETAS,
                "to_fill": [{"connector": s, "placeholder": placeholder(s)} for s in to_fill],
                "files": {p: hashlib.sha256(t.encode("utf-8")).hexdigest() for p, t in sorted(files.items())}}
    files["manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


def write(out: Path | str, overrides: dict[str, str] | None = None, root: Path = ROOT) -> list[str]:
    from .util import write_if_changed

    out = Path(out)
    files = build(overrides, root)
    changed = [p for p, text in files.items() if write_if_changed(out / p, text.encode("utf-8"))]
    return changed
